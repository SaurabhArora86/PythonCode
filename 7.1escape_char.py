# Escape characters in Python

# Escape characters are used to insert characters that are illegal in a string.
# For example, to include a double quote inside a string that is enclosed in double quotes, you can use the escape character \".

# Examples of escape characters:
print("He said, \"Hello, World!\"")  # Output: He said, "Hello, World!"
print('It\'s a beautiful day!')      # Output: It's a beautiful day!

# Common escape characters:
# \'  - Single Quote
# \"  - Double Quote
# \\  - Backslash
# \n  - New Line
# \r  - Carriage Return
# \t  - Tab
# \b  - Backspace
# \f  - Form Feed
# \ooo - Octal value
# \xhh - Hex value

# Example usage:
print("Line1\nLine2")  # Output: Line1
#         Line2

print("Column1\tColumn2")  # Output: Column1    Column2

print("Backslash: \\")  # Output: Backslash: \
